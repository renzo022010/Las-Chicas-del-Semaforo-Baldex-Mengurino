import cv2
import numpy as np
from PIL import Image
from contador import locate_plate,read_image,save_image
ROOT=Path(__file__).resolve().parent

@dataclass(frozen=True)
class NeuralConfig:
    box_threshold:float=.25
    nms_iou:float=.6
    mask_duplicate_iou:float=.8
    min_roi_fraction:float=.5
    border_margin:float=0.0
    max_side:int=1400
    batch_size:int=8
    device:str='cuda'
    def validate(self):
        for name in ('box_threshold','nms_iou','mask_duplicate_iou','min_roi_fraction'):
            value=getattr(self,name)
            if not math.isfinite(value) or not 0<value<=1: raise ValueError(name+' fuera de rango')
        if not 0<=self.border_margin<.3 or self.max_side<256 or self.batch_size<1:
            raise ValueError('Tamano, margen o lote invalidos')
        if self.device not in ('cuda','cpu'): raise ValueError('Dispositivo invalido')

def plate_region(im,margin,roi=None,scale=1.):
    h,w=im.shape[:2]
    if roi is None:
        (cx,cy,rx,ry,angle),method=locate_plate(im)
    else:
        x,y,r=roi
        if not all(math.isfinite(v) for v in roi) or r<=0 or not (0<=x*scale<w and 0<=y*scale<h):
            raise ValueError('ROI manual invalida')
        cx,cy,rx,ry,angle=x*scale,y*scale,r*scale,r*scale,0.
        method='manual'
    rx*=1-margin;ry*=1-margin
    yy,xx=np.ogrid[:h,:w];a=math.radians(angle)
    u=((xx-cx)*math.cos(a)+(yy-cy)*math.sin(a))/rx
    v=(-(xx-cx)*math.sin(a)+(yy-cy)*math.cos(a))/ry
    radial=u*u+v*v;valid=radial<=1
    if valid.sum()<100:raise ValueError('Region de placa demasiado pequena')
    ex=math.sqrt((rx*math.cos(a))**2+(ry*math.sin(a))**2)*1.03
    ey=math.sqrt((rx*math.sin(a))**2+(ry*math.cos(a))**2)*1.03
    crop=(max(0,int(cx-ex)),max(0,int(cy-ey)),min(w,math.ceil(cx+ex)),min(h,math.ceil(cy+ey)))
    return valid,radial,(cx,cy,rx,ry,angle),method,crop

def compact_mask(mask):
    x,y,w,h=cv2.boundingRect(mask.astype(np.uint8))
    return (x,y,w,h,mask[y:y+h,x:x+w].copy(),int(np.count_nonzero(mask)))

def duplicate_mask(candidate,accepted,threshold):
    x,y,w,h,mask,area=candidate
    for ox,oy,ow,oh,other,other_area in accepted:
        left,top=max(x,ox),max(y,oy)
        right,bottom=min(x+w,ox+ow),min(y+h,oy+oh)
        if left>=right or top>=bottom:continue
        # Skip pairs whose maximum possible intersection cannot reach the threshold.
        upper=min((right-left)*(bottom-top),area,other_area)
        if upper/max(area+other_area-upper,1)<=threshold:continue
        inter=np.count_nonzero(mask[top-y:bottom-y,left-x:right-x]&other[top-oy:bottom-oy,left-ox:right-ox])
        if inter/max(area+other_area-inter,1)>threshold:return True
    return False

class HybridCounter:
    def __init__(self,config=NeuralConfig()):
        config.validate();self.config=config
        start=time.perf_counter()
        sys.path.insert(0,str(ROOT/'vendor/GroundingDINO'))
        import torch
        from groundingdino.models import build_model
        from groundingdino.util.slconfig import SLConfig
        from groundingdino.util.misc import clean_state_dict
        from sam2.build_sam import build_sam2
        from sam2.sam2_image_predictor import SAM2ImagePredictor
        import groundingdino.datasets.transforms as T
        self.torch=torch
        if config.device=='cuda' and not torch.cuda.is_available():
            raise RuntimeError('GPU CUDA no disponible; usar --device cpu o revisar entorno neural.')
        args=SLConfig.fromfile(str(ROOT/'vendor/GroundingDINO/groundingdino/config/GroundingDINO_SwinT_OGC.py'))
        args.device=config.device
        args.text_encoder_type=str(ROOT/'modelos/bert-base-uncased')
        args.use_checkpoint=False;args.use_transformer_ckpt=False
        self.detector=build_model(args)
        with torch.serialization.safe_globals([argparse.Namespace]):
            checkpoint=torch.load(ROOT/'modelos/colony_gd.pth',map_location='cpu',weights_only=True)
        state=clean_state_dict(checkpoint['model'])
        mismatch=self.detector.load_state_dict(state,strict=False)
        # position_ids are regenerated by newer transformers; learned weights must match.
        bad_missing=[k for k in mismatch.missing_keys if not k.endswith('position_ids')]
        bad_extra=[k for k in mismatch.unexpected_keys if not k.endswith('position_ids')]
        if bad_missing or bad_extra:
            raise RuntimeError(f'Pesos incompatibles: missing={bad_missing}, unexpected={bad_extra}')
        del checkpoint,state
        self.detector.eval().to(config.device)
        sam=build_sam2('configs/sam2/sam2_hiera_l.yaml',str(ROOT/'modelos/sam2_hiera_large.pt'),device=config.device,apply_postprocessing=False)
        self.segmenter=SAM2ImagePredictor(sam,max_hole_area=0,max_sprinkle_area=0)
        self.transform=T.Compose([T.RandomResize([800],max_size=1333),T.ToTensor(),T.Normalize([.485,.456,.406],[.229,.224,.225])])
        if config.device=='cuda':torch.cuda.synchronize()
        self.load_seconds=round(time.perf_counter()-start,3)
        self.hardware=torch.cuda.get_device_name(0) if config.device=='cuda' else 'CPU'

    def count(self,bgr,roi=None):
        torch=self.torch;cfg=self.config
        from torchvision.ops import box_convert,nms
        start=time.perf_counter()
        if cfg.device=='cuda':torch.cuda.reset_peak_memory_stats()
        h0,w0=bgr.shape[:2];scale=min(1.,cfg.max_side/max(h0,w0))
        im=cv2.resize(bgr,None,fx=scale,fy=scale,interpolation=cv2.INTER_AREA)
        rgb=cv2.cvtColor(im,cv2.COLOR_BGR2RGB);h,w=im.shape[:2]
        valid,radial,ellipse,roi_method,crop=plate_region(im,cfg.border_margin,roi,scale)
        cx,cy,rx,ry,angle=ellipse;x1,y1,x2,y2=crop
        tensor,_=self.transform(Image.fromarray(rgb[y1:y2,x1:x2]),None)
        with torch.inference_mode():
            pred=self.detector(tensor[None].to(cfg.device),captions=['microbial colony.'])
        scores=pred['pred_logits'][0].sigmoid().max(dim=-1).values.cpu()
        boxes=pred['pred_boxes'][0].cpu();chosen=scores>cfg.box_threshold
        boxes=box_convert(boxes[chosen],in_fmt='cxcywh',out_fmt='xyxy')
        boxes*=torch.tensor([x2-x1,y2-y1,x2-x1,y2-y1])
        boxes+=torch.tensor([x1,y1,x1,y1]);scores=scores[chosen]
        boxes[:,0::2].clamp_(0,w);boxes[:,1::2].clamp_(0,h)
        raw_count=len(boxes)
        keep=nms(boxes,scores,cfg.nms_iou)
        boxes=boxes[keep].numpy();scores=scores[keep].numpy()
        del pred,tensor
        detection_seconds=time.perf_counter()-start
        instances=np.zeros((h,w),np.uint16);detections=[];rejected=[]
        accepted_masks=[]
        from contextlib import nullcontext
        context=torch.autocast('cuda',dtype=torch.bfloat16) if cfg.device=='cuda' else nullcontext()
        with torch.inference_mode(),context:
            if len(boxes):self.segmenter.set_image(rgb)
            for offset in range(0,len(boxes),cfg.batch_size):
                batch=boxes[offset:offset+cfg.batch_size]
                masks,quality,_=self.segmenter.predict(box=batch,point_coords=None,point_labels=None,multimask_output=False)
                masks=np.asarray(masks).reshape(len(batch),h,w)
                quality=np.asarray(quality).reshape(len(batch),-1)[:,0]
                for j,mask in enumerate(masks):
                    idx=offset+j;mask=mask.astype(bool);area=int(mask.sum())
                    inside=mask&valid
                    fraction=float(inside.sum()/max(area,1))
                    compact=compact_mask(inside)
                    reason=None
                    if area<10:reason='empty_or_tiny_mask'
                    elif fraction<cfg.min_roi_fraction:reason='outside_plate'
                    elif duplicate_mask(compact,accepted_masks,cfg.mask_duplicate_iou):
                        reason='duplicate_mask'
                    if reason:
                        rejected.append({'reason':reason,'score':float(scores[idx]),'box':(boxes[idx]/scale).tolist()});continue
                    # High-score instances own overlapping pixels in the exported label map.
                    visible=inside&(instances==0)
                    if visible.sum()<10:
                        rejected.append({'reason':'fully_overlapped','score':float(scores[idx])});continue
                    ident=len(detections)+1;instances[visible]=ident;accepted_masks.append(compact)
                    bx1,by1,bx2,by2=boxes[idx];px,py=(bx1+bx2)/2,(by1+by2)/2
                    near_edge=bool(radial[min(h-1,max(0,round(py))),min(w-1,max(0,round(px)))]>.88**2)
                    detections.append({'id':ident,'x':round(float(px/scale),2),'y':round(float(py/scale),2),
                        'bbox':[round(float(v/scale),2) for v in (bx1,by1,bx2-bx1,by2-by1)],
                        'radius':round(math.sqrt(inside.sum()/math.pi)/scale,2),
                        'instance_area':round(float(visible.sum()/scale**2),2),'score':round(float(scores[idx]),5),
                        'sam_quality':round(float(quality[j]),5),'roi_fraction':round(fraction,4),'near_edge':near_edge})
        annotated=im.copy();cv2.ellipse(annotated,((cx,cy),(2*rx,2*ry),angle),(255,180,0),2)
        for det in detections:
            contour,_=cv2.findContours((instances==det['id']).astype(np.uint8),cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
            cv2.drawContours(annotated,contour,-1,(0,190,255) if det['near_edge'] else (0,230,80),2)
            pt=(round(det['x']*scale),round(det['y']*scale))
            cv2.circle(annotated,pt,2,(0,0,255),-1)
            cv2.putText(annotated,str(det['id']),(pt[0]+4,pt[1]-4),cv2.FONT_HERSHEY_SIMPLEX,.4,(0,40,255),1,cv2.LINE_AA)
        cv2.rectangle(annotated,(0,0),(w,44),(30,30,30),-1)
        cv2.putText(annotated,f'Hibrido: {len(detections)} candidatos | Revisar',(10,29),cv2.FONT_HERSHEY_SIMPLEX,.65,(255,255,255),2,cv2.LINE_AA)
        palette=np.random.default_rng(42).integers(55,255,size=(len(detections)+1,3),dtype=np.uint8);palette[0]=0
        warnings=['Conteo experimental: requiere revision humana. No identifica especies.',
          'Los scores del detector no son probabilidades calibradas.',
          'Pesos ajustados con AGAR: estas fotos no demuestran generalizacion independiente.']
        if roi_method=='fallback':warnings.append('Delimitacion automatica no fiable; usar --roi X Y RADIO.')
        if not detections:warnings.append('Cero candidatos no demuestra ausencia de colonias.')
        if cfg.device=='cuda':torch.cuda.synchronize()
        result={'version':'0.3.0','method':'opencv_colony_grounding_dino_sam2','count':len(detections),'requires_review':True,
          'image_size':{'width':w0,'height':h0},'analysis_scale':scale,'detections':detections,
          'roi':{'x':cx/scale,'y':cy/scale,'analysis_axes':[rx/scale,ry/scale],'angle_degrees':angle,'method':roi_method},
          'config':asdict(cfg),'raw_box_count':raw_count,'after_nms_count':len(boxes),'rejected':rejected,
          'processing_seconds':round(time.perf_counter()-start,3),'detection_seconds':round(detection_seconds,3),
          'model_load_seconds':self.load_seconds,'hardware':self.hardware,
          'peak_gpu_allocated_mb':round(torch.cuda.max_memory_allocated()/1024**2,1) if cfg.device=='cuda' else None,
          'warnings':warnings,'model_sources':json.loads((ROOT/'modelos/manifest.json').read_text(encoding='utf-8'))}
        debug={'annotated':annotated,'roi':valid.astype(np.uint8)*255,'mask':(instances>0).astype(np.uint8)*255,'instances':instances,'segments':palette[instances]}
        return result,debug

def write_hybrid_result(result,debug,output,stem):
    output=Path(output);output.mkdir(parents=True,exist_ok=True)
    (output/f'{stem}_resultado.json').write_text(json.dumps(result,indent=2,ensure_ascii=False),encoding='utf-8')
    save_image(output/f'{stem}_conteo.jpg',debug['annotated'])
    for key in ('roi','mask','instances','segments'):save_image(output/f'{stem}_{key}.png',debug[key])

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('image',type=Path);p.add_argument('--output',type=Path,default=ROOT/'resultados/hibrido_individual')
    p.add_argument('--device',choices=['cuda','cpu'],default='cuda');p.add_argument('--box-threshold',type=float,default=.25)
    p.add_argument('--batch-size',type=int,default=8);p.add_argument('--roi',nargs=3,type=float,metavar=('X','Y','RADIO'))
    a=p.parse_args()
    try:
        image=read_image(a.image)
        model=HybridCounter(NeuralConfig(device=a.device,box_threshold=a.box_threshold,batch_size=a.batch_size))
        result,debug=model.count(image,tuple(a.roi) if a.roi else None)
        result['input_image']=str(a.image.resolve());write_hybrid_result(result,debug,a.output,a.image.stem)
    except (ValueError,OSError,RuntimeError) as exc:p.exit(2,f'Error: {exc}\n')
    print(json.dumps({k:result[k] for k in ['count','processing_seconds','model_load_seconds','peak_gpu_allocated_mb','hardware']},indent=2))
if __name__=='__main__':main()
